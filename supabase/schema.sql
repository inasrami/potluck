
create table if not exists public.recipes (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) > 0),
  description text not null,
  category text not null,
  cook_time_minutes int not null check (cook_time_minutes > 0),
  ingredients text not null,
  instructions text not null,
  image_url text,
  author_name text not null,
  owner_id uuid not null references auth.users(id) default auth.uid(),
  created_at timestamptz not null default now());
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  recipe_id bigint not null references public.recipes(id) on delete cascade,
  comment text not null check (length(trim(comment)) > 0),
  author_name text not null,
  owner_id uuid not null references auth.users(id) default auth.uid(),
  created_at timestamptz not null default now());
alter table public.recipes enable row level security;
alter table public.comments enable row level security;
revoke all privileges on public.recipes, public.comments from anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select on public.recipes, public.comments to anon, authenticated;
grant insert, update, delete on public.recipes to authenticated;
grant insert on public.comments to authenticated;
create policy recipes_read on public.recipes for select to anon, authenticated using (true);
create policy recipes_create on public.recipes for insert to authenticated with check (owner_id = (select auth.uid()));
create policy recipes_edit on public.recipes for update to authenticated using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
create policy recipes_delete on public.recipes for delete to authenticated using (owner_id = (select auth.uid()));
create policy comments_read on public.comments for select to anon, authenticated using (true);
create policy comments_create on public.comments for insert to authenticated with check (owner_id = (select auth.uid()) and length(trim(comment)) > 0);
